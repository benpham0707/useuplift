// Debug panel — shows the state every reviewer cares about.
// ---------------------------------------------------------------------------

interface DebugPanelProps {
  readonly smartOrder: readonly string[];
  readonly selectedSentenceId: string | null;
  readonly position: { readonly index: number; readonly total: number };
  readonly reviewedCount: number;
  readonly totalCount: number;
  readonly navStackDepth: number;
  readonly canNext: boolean;
  readonly canPrev: boolean;
  readonly endOfReviewReached: boolean;
  readonly lastAnnouncement: string | null;
}

function DebugPanel(props: DebugPanelProps) {
  return (
    <section
      style={{
        border: '1px solid hsl(220 15% 85%)',
        background: 'white',
        borderRadius: 8,
        padding: 16,
        marginBottom: 20,
        fontFamily: TYPOGRAPHY.families.sans,
        fontSize: TYPOGRAPHY.size.panelHeader,
        lineHeight: 1.6,
        color: 'hsl(220 15% 25%)',
      }}
    >
      <h3
        style={{
          margin: '0 0 8px 0',
          fontSize: TYPOGRAPHY.size.overviewLabel,
          fontWeight: TYPOGRAPHY.weight.semibold,
          color: 'hsl(220 20% 20%)',
        }}
      >
        Debug
      </h3>
      <Row label="selected" value={props.selectedSentenceId ?? '(none)'} />
      <Row
        label="position"
        value={`${props.position.index + 1} of ${props.position.total}`}
      />
      <Row
        label="reviewed"
        value={`${props.reviewedCount} / ${props.totalCount}`}
      />
      <Row label="navStack depth" value={String(props.navStackDepth)} />
      <Row
        label="canPrev / canNext"
        value={`${props.canPrev} / ${props.canNext}`}
      />
      <Row
        label="endOfReview"
        value={props.endOfReviewReached ? 'reached' : 'not yet'}
      />
      <Row
        label="last announce"
        value={props.lastAnnouncement ?? '(none)'}
      />
      <Row label="order length" value={String(props.smartOrder.length)} />
    </section>
  );
}

function Row({
  label,
  value,
}: {
  readonly label: string;
  readonly value: string;
}) {
  return (
    <div style={{ display: 'flex', gap: 8, alignItems: 'baseline' }}>
      <span
        style={{
          color: 'hsl(220 10% 55%)',
          fontSize: TYPOGRAPHY.size.meta,
          letterSpacing: TYPOGRAPHY.tracking.meta,
          minWidth: 140,
        }}
      >
        {label}
      </span>
      <code
        style={{
          fontFamily: 'ui-monospace, SFMono-Regular, monospace',
          fontSize: TYPOGRAPHY.size.meta,
        }}
      >
        {value}
      </code>
    </div>
  );
}

interface OrderListProps {
  readonly order: readonly string[];
  readonly selectedSentenceId: string | null;
  readonly onJump: (sentenceId: string) => void;
  readonly isViewed: (sentenceId: string) => boolean;
  readonly priorityScores: ReadonlyMap<string, number>;
}

function OrderList(props: OrderListProps) {
  return (
    <section
      style={{
        border: '1px solid hsl(220 15% 85%)',
        background: 'white',
        borderRadius: 8,
        padding: 16,
        fontFamily: TYPOGRAPHY.families.sans,
      }}
    >
      <h3
        style={{
          margin: '0 0 12px 0',
          fontSize: TYPOGRAPHY.size.overviewLabel,
          fontWeight: TYPOGRAPHY.weight.semibold,
          color: 'hsl(220 20% 20%)',
        }}
      >
        Smart order (click to jump — resets nav stack)
      </h3>
      <ol style={{ listStyle: 'none', margin: 0, padding: 0 }}>
        {props.order.map((id, i) => {
          const sentence = sampleProfile.sentences.find((s) => s.id === id);
          const score = props.priorityScores.get(id) ?? 0;
          const viewed = props.isViewed(id);
          const selected = id === props.selectedSentenceId;
          return (
            <li key={id} style={{ marginBottom: 4 }}>
              <button
                type="button"
                onClick={() => props.onJump(id)}
                style={{
                  width: '100%',
                  textAlign: 'left',
                  padding: '6px 8px',
                  borderRadius: 6,
                  border: `1px solid ${selected ? 'hsl(145 25% 50%)' : 'hsl(220 15% 90%)'}`,
                  background: selected ? 'hsl(145 35% 96%)' : 'white',
                  color: 'hsl(220 15% 25%)',
                  fontSize: TYPOGRAPHY.size.panelHeader,
                  fontFamily: TYPOGRAPHY.families.sans,
                  cursor: 'pointer',
                  opacity: viewed ? 0.55 : 1,
                  display: 'flex',
                  gap: 8,
                  alignItems: 'baseline',
                }}
              >
                <code style={{ minWidth: 32, color: 'hsl(220 10% 50%)' }}>
                  {i + 1}.
                </code>
                <code style={{ minWidth: 48 }}>{id}</code>
                {sentence ? (
                  <span
                    style={{
                      color: 'hsl(220 10% 45%)',
                      fontSize: TYPOGRAPHY.size.meta,
                      letterSpacing: TYPOGRAPHY.tracking.meta,
                    }}
                  >
                    {TIER_META[sentence.tier].label}
                  </span>
                ) : null}
                <span
                  style={{
                    marginLeft: 'auto',
                    color: 'hsl(220 10% 50%)',
                    fontSize: TYPOGRAPHY.size.meta,
                  }}
                >
                  score {score.toFixed(3)}
                </span>
              </button>
            </li>
          );
        })}
      </ol>
    </section>
  );
}
